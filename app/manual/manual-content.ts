export const MANUAL_GUIDES = { STUDENT, PARENT, TEACHER_SEMI, TEACHER_DEDICATED, TEACHER_ATTENDANCE_ONLY, APPROVER_TEACHER, ATTENDANCE_ADMIN, SCHOOL_ADMIN, MASTER };

const ATTENDANCE_ADMIN_ROLES = ['attendance_admin', 'attendance_only', 'attendance_manager'];

/** ログイン中のアカウントに合うマニュアル（複数の役割を持つ場合は複数）。 */
export function manualGuidesFor(profile: Record<string, any>): ManualGuide[] {
  const role = String(profile.role || '').toLowerCase();
  if (role === 'student') return [STUDENT];
  if (role === 'parent' || role === 'guardian') return [PARENT];
  if (role === 'master') return [MASTER, ATTENDANCE_ADMIN];
  if (ATTENDANCE_ADMIN_ROLES.includes(role)) return [ATTENDANCE_ADMIN];
  if (role === 'teacher') {
    const guides: ManualGuide[] = [];
    if (isDedicatedProfile(profile)) guides.push(TEACHER_DEDICATED);
    else guides.push(hasScienceSocialProgram(profile) ? TEACHER_SEMI : TEACHER_ATTENDANCE_ONLY);
    if (isDedicatedAttendanceApproverProfile(profile)) guides.push(APPROVER_TEACHER);
    return guides;
  }
  const guides = [SCHOOL_ADMIN];
  if (profile.admin_permissions?.attendance === true) guides.push(ATTENDANCE_ADMIN);
  return guides;
}

